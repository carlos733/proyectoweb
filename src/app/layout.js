
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import "./encabezado.css";
import RegistrarSW from "./Componentes/RegistrarSW";
import Link from "next/link";
import { createClient } from "./lib/supServer";
import { cerrarSesion } from "./actions/authAction";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }) {

  // Obtener el usuario de Supabase
  const supabase = await createClient();

  const {
    data: { user },
  } = await supabase.auth.getUser();

  return (
    <html
      lang="es"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">

       

  <header className="encabezado">

    <Link href="/" className="encabezado-marca">
      Mi primera app web
    </Link>

{user && (
    <header className="encabezado">

        <Link href="/" className="encabezado-marca">
            Mi primera app web
        </Link>

        <nav className="encabezado-nav">

            <Link href="/" className="nav-enlace">
                Inicio
            </Link>

            <Link href="/Productos" className="nav-enlace">
                Productos
            </Link>

            <Link href="/Contacto" className="nav-enlace">
                Contacto
            </Link>

            <form action={cerrarSesion}>
                <button type="submit" className="nav-enlace">
                    Cerrar sesión
                </button>
            </form>

        </nav>

    </header>
)}

  </header>



   

        <RegistrarSW />

        {children}

      </body>
    </html>
  );
}
